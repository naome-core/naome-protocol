CREATE TABLE IF NOT EXISTS rep2_pages(id TEXT PRIMARY KEY, data BLOB NOT NULL) WITHOUT ROWID;
CREATE TABLE IF NOT EXISTS rep2_heads(id TEXT PRIMARY KEY, data BLOB NOT NULL) WITHOUT ROWID;
CREATE TABLE IF NOT EXISTS rep2_jumps(head TEXT,level INTEGER,ancestor TEXT NOT NULL,PRIMARY KEY(head,level)) WITHOUT ROWID;
CREATE TABLE IF NOT EXISTS rep2_packs(id INTEGER PRIMARY KEY,data BLOB NOT NULL);
CREATE TABLE IF NOT EXISTS rep2_records(id TEXT PRIMARY KEY,pack INTEGER NOT NULL,start INTEGER NOT NULL,length INTEGER NOT NULL,access TEXT NOT NULL) WITHOUT ROWID;
CREATE INDEX IF NOT EXISTS rep2_withdrawals ON objects(id) WHERE data IS NULL;
CREATE TABLE IF NOT EXISTS rep2_shared(head TEXT PRIMARY KEY REFERENCES rep2_heads(id)) WITHOUT ROWID;
CREATE TABLE IF NOT EXISTS rep2_receipts(id TEXT PRIMARY KEY,data BLOB NOT NULL) WITHOUT ROWID;
CREATE TABLE IF NOT EXISTS rep2_tips(source TEXT,head TEXT,PRIMARY KEY(source,head)) WITHOUT ROWID;
